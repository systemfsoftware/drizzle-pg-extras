const url = process.env.TIMESCALE_URL
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../.tmp')
const kit = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../node_modules/drizzle-kit/bin.cjs')
const source = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../src/index.ts')
const manifestPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../package.json')
const manifestVersion = (JSON.parse(readFileSync(manifestPath, 'utf8')) as { version: string }).version

describe.skipIf(!url)('timescaledb hypertables', () => {
  it('migrates a hypertable through drizzle-kit and leaves no schema diff', async () => {
    mkdirSync(root, { recursive: true })
    const dir = mkdtempSync(path.join(root, 'ts-'))
    writeFileSync(path.join(dir, 'schema.ts'), schemaSource(source))
    writeFileSync(path.join(dir, 'drizzle.config.ts'), configSource())

    const client = new pg.Client({ connectionString: url })
    await client.connect()
    const cwd = process.cwd()
    try {
      await reset(client)
      const table = kitExec(dir, ['generate', '--name', 'metrics', '--config', 'drizzle.config.ts'])
      expect(table.status, table.stderr + table.stdout).toBe(0)

      process.chdir(dir)
      expect(await run(['generate', '--name', 'hypertables'])).toBe(0)
      process.chdir(cwd)

      const migrate = kitExec(dir, ['migrate', '--config', 'drizzle.config.ts'])
      expect(migrate.status, migrate.stderr + migrate.stdout).toBe(0)

      const upPath = migrationFile(path.join(dir, 'drizzle'), 'hypertables')
      const upSql = readFileSync(upPath, 'utf8')
      expect(upSql).toContain('CREATE EXTENSION IF NOT EXISTS "timescaledb"')
      expect(upSql.indexOf('CREATE EXTENSION')).toBeLessThan(upSql.indexOf('create_hypertable'))
      expect(upSql).toContain('if_not_exists => TRUE')
      expect(upSql).toContain(`partition_interval => INTERVAL '1 day'`)
      expect(upSql).toContain("by_hash('device_id'::name, 4)")
      expect(upSql).toContain('add_retention_policy')
      expect(upSql).toContain('add_columnstore_policy')
      expect(upSql).toContain(`Generated by drizzle-pg-extras ${manifestVersion}`)
      await runStatements(client, upSql)

      expect(await intervalEquals(client, 'public', 'metrics', 'time', '1 day')).toBe(true)
      expect(await partitionsOf(client, 'public', 'metrics', 'device_id')).toBe(4)
      expect(await intervalEquals(client, 'market', 'readings', 'time', '1 hour')).toBe(true)
      expect(await columnstoreEnabled(client, 'public', 'metrics')).toBe(true)
      const settings = await client.query<{ segmentby: string; orderby: string }>(
        `SELECT segmentby, orderby FROM timescaledb_information.hypertable_columnstore_settings
         WHERE hypertable = 'public.metrics'::regclass`,
      )
      expect(settings.rows[0]?.segmentby).toContain('device_id')
      expect(settings.rows[0]?.orderby).toContain('DESC')
      expect(await policyInterval(client, 'metrics', 'policy_retention', 'drop_after', '6 months')).toBe(true)
      expect(await policyInterval(client, 'metrics', 'policy_compression', 'compress_after', '7 days')).toBe(
        true,
      )
      const schedule = await client.query<{ matches: boolean }>(
        `SELECT schedule_interval = INTERVAL '1 day' AS matches
         FROM timescaledb_information.jobs
         WHERE hypertable_name = 'metrics' AND proc_name = 'policy_retention'`,
      )
      expect(schedule.rows[0]?.matches).toBe(true)

      await client.query(
        `INSERT INTO metrics (time, device_id, value) VALUES (now(), 'device-a', 1), (now() - INTERVAL '3 days', 'device-b', 2)`,
      )
      const inserted = await client.query<{ chunks: string }>(
        `SELECT count(*)::text AS chunks FROM timescaledb_information.chunks
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics'`,
      )
      expect(Number(inserted.rows[0]?.chunks)).toBeGreaterThan(0)

      const oldChunk = await client.query<{ chunk: string }>(
        `SELECT show_chunks('public.metrics'::regclass, older_than => now() - INTERVAL '2 days')::text AS chunk LIMIT 1`,
      )
      await client.query(`CALL convert_to_columnstore($1::regclass)`, [oldChunk.rows[0]!.chunk])
      expect(await columnstoreChunkCount(client, 'public', 'metrics')).toBe(1)
      expect(await chunkCount(client, 'public', 'metrics')).toBe(2)

      const before = sqlFiles(path.join(dir, 'drizzle'))
      const again = kitExec(dir, ['generate', '--name', 'noop', '--config', 'drizzle.config.ts'])
      expect(again.status, again.stderr + again.stdout).toBe(0)
      expect(again.stdout).toContain('No schema changes')
      expect(sqlFiles(path.join(dir, 'drizzle'))).toEqual(before)

      process.chdir(dir)
      expect(await run(['generate', '--name', 'again'])).toBe(0)
      process.chdir(cwd)
      expect(sqlFiles(path.join(dir, 'drizzle'))).toEqual(before)

      writeFileSync(
        path.join(dir, 'schema.ts'),
        schemaSource(source, { chunk: '2 days', dropAfter: '3 months', direction: 'asc', reorder: true }),
      )
      process.chdir(dir)
      expect(await run(['generate', '--name', 'chunk_interval'])).toBe(0)
      process.chdir(cwd)
      const follow = kitExec(dir, ['migrate', '--config', 'drizzle.config.ts'])
      expect(follow.status, follow.stderr + follow.stdout).toBe(0)
      const changedSql = readFileSync(migrationFile(path.join(dir, 'drizzle'), 'chunk_interval'), 'utf8')
      expect(changedSql).toContain('set_chunk_time_interval')
      expect(changedSql).toContain("INTERVAL '2 days'")
      expect(changedSql).toContain("INTERVAL '3 months'")
      expect(changedSql).toContain('add_reorder_policy')
      expect(changedSql).toContain(`timescaledb.orderby = '"time" ASC'`)
      expect(changedSql).not.toContain('create_hypertable')
      await runStatements(client, changedSql)

      const reorder = await client.query(
        `SELECT 1 FROM timescaledb_information.jobs WHERE proc_name = 'policy_reorder' AND hypertable_name = 'metrics'`,
      )
      expect(reorder.rowCount).toBe(1)

      expect(await intervalEquals(client, 'public', 'metrics', 'time', '2 days')).toBe(true)
      expect(await policyInterval(client, 'metrics', 'policy_retention', 'drop_after', '3 months')).toBe(true)

      await runStatements(
        client,
        readFileSync(migrationFile(path.join(dir, 'drizzle'), 'chunk_interval', 'down'), 'utf8'),
      )
      expect(await intervalEquals(client, 'public', 'metrics', 'time', '1 day')).toBe(true)
      expect(await policyInterval(client, 'metrics', 'policy_retention', 'drop_after', '6 months')).toBe(true)

      await runStatements(client, readFileSync(migrationFile(path.join(dir, 'drizzle'), 'hypertables', 'down'), 'utf8'))
      expect(await columnstoreEnabled(client, 'public', 'metrics')).toBe(false)
      expect(await columnstoreChunkCount(client, 'public', 'metrics')).toBe(0)
      const kept = await client.query<{ device_id: string; value: number }>(
        `SELECT device_id, value FROM metrics ORDER BY value`,
      )
      expect(kept.rows).toEqual([{ device_id: 'device-a', value: 1 }, { device_id: 'device-b', value: 2 }])
      const jobs = await client.query(`SELECT 1 FROM timescaledb_information.jobs WHERE hypertable_name = 'metrics'`)
      expect(jobs.rowCount).toBe(0)
      const still = await client.query(
        `SELECT 1 FROM timescaledb_information.hypertables
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics'`,
      )
      expect(still.rowCount).toBe(1)
      const extension = await client.query(`SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'`)
      expect(extension.rowCount).toBe(1)

      const finalKit = kitExec(dir, ['generate', '--name', 'still_noop', '--config', 'drizzle.config.ts'])
      expect(finalKit.status, finalKit.stderr + finalKit.stdout).toBe(0)
      expect(finalKit.stdout).toContain('No schema changes')
    } finally {
      process.chdir(cwd)
      await client.end()
    }
  })

  it('refuses a non-empty table unless migrateData is set', async () => {
    const client = new pg.Client({ connectionString: url })
    await client.connect()
    try {
      await reset(client)
      await client.query(`CREATE EXTENSION IF NOT EXISTS timescaledb`)
      await client.query(`
        CREATE TABLE occupied (
          "time" timestamp with time zone NOT NULL,
          "value" integer NOT NULL
        )
      `)
      await client.query(`INSERT INTO occupied ("time", "value") VALUES ('2024-06-01', 1)`)
      await expect(client.query(hypertableSql(false))).rejects.toThrow(/not empty/)
      const moved = hypertableSql(true)
      await client.query(moved)
      await client.query(moved)
      const count = await client.query<{ count: string }>(`SELECT count(*)::text AS count FROM occupied`)
      expect(count.rows[0]?.count).toBe('1')
      const kind = await client.query(
        `SELECT 1 FROM timescaledb_information.hypertables WHERE hypertable_schema = 'public' AND hypertable_name = 'occupied'`,
      )
      expect(kind.rowCount).toBe(1)
    } finally {
      await client.end()
    }
  })
})

describe.skipIf(!url)('timescaledb continuous aggregates', () => {
  it('migrates a hierarchical continuous aggregate stack and rebuilds a leaf', async () => {
    mkdirSync(root, { recursive: true })
    const dir = mkdtempSync(path.join(root, 'cagg-'))
    writeFileSync(path.join(dir, 'schema.ts'), aggregateSchemaSource(source))
    writeFileSync(path.join(dir, 'drizzle.config.ts'), configSource())

    const client = new pg.Client({ connectionString: url })
    await client.connect()
    const cwd = process.cwd()
    try {
      await client.query('DROP MATERIALIZED VIEW IF EXISTS public.metrics_daily CASCADE')
      await client.query('DROP MATERIALIZED VIEW IF EXISTS public.metrics_hourly CASCADE')
      await client.query('DROP TABLE IF EXISTS public.metrics CASCADE')

      const table = kitExec(dir, ['generate', '--name', 'metrics', '--config', 'drizzle.config.ts'])
      expect(table.status, table.stderr + table.stdout).toBe(0)

      process.chdir(dir)
      expect(await run(['generate', '--name', 'aggregates'])).toBe(0)
      process.chdir(cwd)

      const migrate = kitExec(dir, ['migrate', '--config', 'drizzle.config.ts'])
      expect(migrate.status, migrate.stderr + migrate.stdout).toBe(0)

      const upSql = readFileSync(migrationFile(path.join(dir, 'drizzle'), 'aggregates'), 'utf8')
      expect(upSql).toContain('CREATE MATERIALIZED VIEW IF NOT EXISTS "public"."metrics_hourly"')
      expect(upSql).toContain('CREATE MATERIALIZED VIEW IF NOT EXISTS "public"."metrics_daily"')
      expect(upSql).toContain('WITH NO DATA')
      expect(upSql.indexOf('"public"."metrics_hourly"')).toBeLessThan(upSql.indexOf('"public"."metrics_daily"'))
      await runStatements(client, upSql)

      const views = await client.query<{ view_name: string; materialized_only: boolean }>(
        `SELECT view_name, materialized_only FROM timescaledb_information.continuous_aggregates
         WHERE view_schema = 'public' ORDER BY view_name`,
      )
      expect(views.rows.map((row) => row.view_name)).toEqual(['metrics_daily', 'metrics_hourly'])
      expect(views.rows.every((row) => row.materialized_only === false)).toBe(true)
      const comment = await client.query<{ comment: string | null }>(
        `SELECT obj_description('public.metrics_hourly'::regclass, 'pg_class') AS comment`,
      )
      expect(comment.rows[0]?.comment).toBe('Hourly metrics')

      await client.query(
        `INSERT INTO metrics (time, device_id, value) VALUES (now(), 'a', 1), (now() - INTERVAL '1 minute', 'a', 3)`,
      )
      await client.query(`CALL refresh_continuous_aggregate('public.metrics_hourly', NULL, NULL)`)
      await client.query(`CALL refresh_continuous_aggregate('public.metrics_daily', NULL, NULL)`)
      const refreshed = await client.query<{ value: number }>(`SELECT value FROM metrics_hourly`)
      expect(Number(refreshed.rows[0]?.value)).toBe(2)

      const before = sqlFiles(path.join(dir, 'drizzle'))
      process.chdir(dir)
      expect(await run(['generate', '--name', 'noop'])).toBe(0)
      expect(await run(['check'])).toBe(0)
      process.chdir(cwd)
      expect(sqlFiles(path.join(dir, 'drizzle'))).toEqual(before)

      writeFileSync(path.join(dir, 'schema.ts'), aggregateSchemaSource(source, 'avg', 'avg', '2 hours'))
      process.chdir(dir)
      expect(await run(['generate', '--name', 'chunk_alter'])).toBe(0)
      process.chdir(cwd)
      const chunkAlterSql = readFileSync(migrationFile(path.join(dir, 'drizzle'), 'chunk_alter'), 'utf8')
      expect(chunkAlterSql).toContain("timescaledb.chunk_interval = '2 hours'")
      expect(chunkAlterSql).not.toContain('INTERVAL')
      const chunkAlter = kitExec(dir, ['migrate', '--config', 'drizzle.config.ts'])
      expect(chunkAlter.status, chunkAlter.stderr + chunkAlter.stdout).toBe(0)

      writeFileSync(path.join(dir, 'schema.ts'), aggregateSchemaSource(source, 'max'))
      process.chdir(dir)
      expect(await run(['generate', '--name', 'leaf_rebuild'])).toBe(0)
      process.chdir(cwd)
      const follow = kitExec(dir, ['migrate', '--config', 'drizzle.config.ts'])
      expect(follow.status, follow.stderr + follow.stdout).toBe(0)
      const rebuildSql = readFileSync(migrationFile(path.join(dir, 'drizzle'), 'leaf_rebuild'), 'utf8')
      expect(rebuildSql).toContain('DROP MATERIALIZED VIEW IF EXISTS "public"."metrics_daily"')
      expect(rebuildSql).toContain('CREATE MATERIALIZED VIEW IF NOT EXISTS "public"."metrics_daily"')
      expect(rebuildSql).not.toContain('DROP MATERIALIZED VIEW IF EXISTS "public"."metrics_hourly"')
      await runStatements(client, rebuildSql)

      await runStatements(
        client,
        readFileSync(migrationFile(path.join(dir, 'drizzle'), 'leaf_rebuild', 'down'), 'utf8'),
      )

      writeFileSync(path.join(dir, 'schema.ts'), aggregateSchemaSource(source, 'avg', 'max'))
      process.chdir(dir)
      expect(await run(['generate', '--name', 'parent_change'])).toBe(1)
      process.chdir(cwd)
      expect(sqlFiles(path.join(dir, 'drizzle'))).not.toContain('parent_change')
    } finally {
      process.chdir(cwd)
      await client.end()
    }
  })
})

function aggregateSchemaSource(
  sourcePath: string,
  leafAggregate = 'avg',
  parentAggregate = 'avg',
  chunkInterval = '1 hour',
): string {
  return `import { integer, pgTable, pgView, primaryKey, text, timestamp } from "drizzle-orm/pg-core";
import { continuousAggregate, hypertable, pgExtension, withComment } from ${JSON.stringify(sourcePath)};

export const timescale = pgExtension("timescaledb");

export const metrics = pgTable("metrics", {
  time: timestamp("time", { withTimezone: true }).notNull(),
  deviceId: text("device_id").notNull(),
  value: integer("value").notNull(),
}, (t) => [
  primaryKey({ columns: [t.time, t.deviceId] }),
]);

export const metricsHypertable = hypertable(metrics, {
  timeColumn: metrics.time,
  chunkTimeInterval: "1 day",
});

const hourlyView = withComment(pgView("metrics_hourly", {
  bucket: timestamp("bucket", { withTimezone: true }),
  deviceId: text("device_id"),
  value: integer("value"),
}).existing(), "Hourly metrics");

export const metricsHourly = continuousAggregate(hourlyView, {
  query: \`SELECT time_bucket('1 hour', time) AS bucket, device_id, ${parentAggregate}(value) AS value FROM metrics GROUP BY time_bucket('1 hour', time), device_id\`,
  source: metricsHypertable,
  chunkInterval: "${chunkInterval}",
  refreshPolicies: [{ startOffset: "1 month", endOffset: "1 hour", scheduleInterval: "1 hour" }],
  columnstore: { segmentBy: ["device_id"], orderBy: [{ column: "bucket", direction: "desc" }] },
  columnstorePolicy: { after: "7 days" },
  retention: { dropAfter: "6 months" },
});

const dailyView = pgView("metrics_daily", {
  bucket: timestamp("bucket", { withTimezone: true }),
  deviceId: text("device_id"),
  value: integer("value"),
}).existing();

export const metricsDaily = continuousAggregate(dailyView, {
  query: \`SELECT time_bucket('1 day', bucket) AS bucket, device_id, ${leafAggregate}(value) AS value FROM metrics_hourly GROUP BY time_bucket('1 day', bucket), device_id\`,
  source: metricsHourly,
});
`
}

function hypertableSql(migrateData: boolean): string {
  const occupied = pgTable('occupied', {
    time: timestamp('time', { withTimezone: true }).notNull(),
    value: integer('value').notNull(),
  })
  const snap = snapshotExtras(defineExtras({
    extensions: [pgExtension('timescaledb')],
    hypertables: [hypertable(occupied, { timeColumn: occupied.time, chunkTimeInterval: '1 day', migrateData })],
  }))
  return createHypertableSql(snap.hypertables[0]!)
}

function schemaSource(
  sourcePath: string,
  options?: { chunk?: string; dropAfter?: string; direction?: string; reorder?: boolean },
): string {
  const chunk = options?.chunk ?? '1 day'
  const dropAfter = options?.dropAfter ?? '6 months'
  const direction = options?.direction ?? 'desc'
  return `import { integer, pgSchema, pgTable, text, timestamp, primaryKey } from "drizzle-orm/pg-core";
import { hypertable, pgExtension } from ${JSON.stringify(sourcePath)};

export const timescale = pgExtension("timescaledb");

export const metrics = pgTable("metrics", {
  time: timestamp("time", { withTimezone: true }).notNull(),
  deviceId: text("device_id").notNull(),
  value: integer("value").notNull(),
}, (t) => [
  primaryKey({ columns: [t.time, t.deviceId] }),
]);

export const metricsHypertable = hypertable(metrics, {
  timeColumn: metrics.time,
  chunkTimeInterval: "${chunk}",
  partitioningColumn: metrics.deviceId,
  numberPartitions: 4,
  columnstore: {
    segmentBy: [metrics.deviceId],
    orderBy: [{ column: metrics.time, direction: "${direction}" }],
    sparseIndex: [{ type: "bloom", columns: [metrics.value] }],
  },
  retention: { dropAfter: "${dropAfter}", scheduleInterval: "1 day" },
  columnstorePolicy: { after: "7 days" },
  ${options?.reorder ? 'reorder: "metrics_time_idx",' : ''}
});

export const market = pgSchema("market");

export const readings = market.table("readings", {
  time: timestamp("time", { withTimezone: true, precision: 3 }).notNull(),
  value: integer("value").notNull(),
});

export const readingsHypertable = hypertable(readings, {
  timeColumn: readings.time,
  chunkTimeInterval: "1 hour",
});
`
}

function configSource(): string {
  return `import { defineConfig } from "drizzle-kit";
export default defineConfig({
  dialect: "postgresql",
  schema: "./schema.ts",
  out: "./drizzle",
  dbCredentials: { url: process.env.TIMESCALE_URL! },
});
`
}

async function reset(client: pg.Client): Promise<void> {
  await client.query('DROP SCHEMA IF EXISTS drizzle CASCADE')
  await client.query('DROP SCHEMA IF EXISTS market CASCADE')
  await client.query('DROP TABLE IF EXISTS public.metrics CASCADE')
  await client.query('DROP TABLE IF EXISTS public.occupied CASCADE')
}

async function intervalEquals(
  client: pg.Client,
  schema: string,
  table: string,
  column: string,
  interval: string,
): Promise<boolean> {
  const result = await client.query<{ matches: boolean }>(
    `SELECT time_interval = $4::interval AS matches
     FROM timescaledb_information.dimensions
     WHERE hypertable_schema = $1 AND hypertable_name = $2 AND column_name = $3`,
    [schema, table, column, interval],
  )
  return result.rows[0]?.matches === true
}

async function partitionsOf(client: pg.Client, schema: string, table: string, column: string): Promise<number | null> {
  const result = await client.query<{ num_partitions: number | null }>(
    `SELECT num_partitions FROM timescaledb_information.dimensions
     WHERE hypertable_schema = $1 AND hypertable_name = $2 AND column_name = $3`,
    [schema, table, column],
  )
  const value = result.rows[0]?.num_partitions
  return value === undefined || value === null ? null : Number(value)
}

async function columnstoreEnabled(client: pg.Client, schema: string, table: string): Promise<boolean> {
  const result = await client.query(
    `SELECT 1 FROM timescaledb_information.hypertables
     WHERE hypertable_schema = $1 AND hypertable_name = $2 AND compression_enabled`,
    [schema, table],
  )
  return (result.rowCount ?? 0) > 0
}

async function chunkCount(client: pg.Client, schema: string, table: string): Promise<number> {
  const result = await client.query<{ chunks: string }>(
    `SELECT count(*)::text AS chunks FROM timescaledb_information.chunks
     WHERE hypertable_schema = $1 AND hypertable_name = $2`,
    [schema, table],
  )
  return Number(result.rows[0]?.chunks)
}

async function columnstoreChunkCount(client: pg.Client, schema: string, table: string): Promise<number> {
  const result = await client.query<{ chunks: string }>(
    `SELECT count(*)::text AS chunks FROM timescaledb_information.chunk_columnstore_settings
     WHERE hypertable = format('%I.%I', $1::text, $2::text)::regclass`,
    [schema, table],
  )
  return Number(result.rows[0]?.chunks)
}

async function policyInterval(
  client: pg.Client,
  table: string,
  proc: string,
  key: string,
  interval: string,
): Promise<boolean> {
  const result = await client.query<{ matches: boolean }>(
    `SELECT (config->>$3)::interval = $4::interval AS matches
     FROM timescaledb_information.jobs
     WHERE hypertable_name = $1 AND proc_name = $2`,
    [table, proc, key, interval],
  )
  return result.rows[0]?.matches === true
}

function kitExec(cwd: string, args: string[]) {
  return spawnSync(process.execPath, [kit, ...args], {
    cwd,
    encoding: 'utf8',
    env: process.env,
  })
}

async function runStatements(client: pg.Client, file: string): Promise<void> {
  for (const statement of splitMigrationSql(file)) {
    await client.query(statement)
  }
}

function sqlFiles(dir: string): string[] {
  return migrationTags(dir)
}
